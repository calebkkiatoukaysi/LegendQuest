"""Writes docs/pixel-art-portraits/: a ready-to-paste ChatGPT card for every character's close-up portrait.

    python tools/pixel/portrait_prompts.py           # writes the folder: README.md and one <id>.md per character
    python tools/pixel/portrait_prompts.py --check   # fails if the folder is out of date or the cast list is wrong

The cast and their looks are in tools/pixel/portrait_cast.json. The style block (§2.2) and the expressions' wording
(§4.2) are read from docs/pixel-art-brief.md, so the brief stays the one place they're written; change them there and
run this again.

Each character gets:

- a neutral card, pasted whole into a new chat with the template attached;
- one short edit per expression their tier gets (brief §4.2), pasted in the same chat;
- for each variant look (a disguise, a later costume), an edit that changes the look and the expressions it needs.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BRIEF = os.path.join(ROOT, "docs", "pixel-art-brief.md")
CAST = os.path.join(ROOT, "tools", "pixel", "portrait_cast.json")
OUT = os.path.join(ROOT, "docs", "pixel-art-portraits")

GROUPS = ["Companions", "Main story", "Villains and bosses", "Named supporting", "Minor speakers"]
TIERS = {
    "main": ["angry", "disgust", "smile", "laugh", "sad", "grin", "smirk", "worried", "afraid", "cold", "tired",
             "shock"],
    "named": ["angry", "disgust", "smile", "laugh", "sad", "shock", "worried"],
    "minor": ["angry", "disgust", "smile", "laugh", "sad"],
}
TEMPLATES = ("male", "female")

SIZE = ("SIZE. The attached picture is the template, exactly 1024 by 1024 pixels. Give it back at exactly 1024 by "
        "1024. Paint the character over the grey mannequin exactly where it is, facing straight out: the eyes on the "
        "dashed line across the middle of the head, either side of the dashed centre line; the chin on the dashed "
        "line just under the face; the base of the neck on the dotted line below that; the shoulders filling the "
        "bottom edge; the top of the hair (or hat, hood or helm) inside the dashed box. The dashed lines are only "
        "guides: paint over them, and make the background flat #00FF00 green everywhere else. Don't crop, zoom, "
        "re-centre or re-frame it.")

GENERATED = ("<!-- Generated by tools/pixel/portrait_prompts.py from tools/pixel/portrait_cast.json and the style "
             "block "
             "and expressions in docs/pixel-art-brief.md. Don't edit by hand: change those and run the tool. -->\n\n")

NEUTRAL = "Neutral: calm, eyes open looking straight at the viewer, brows level, mouth closed and relaxed."


def read_brief():
    """The §2.2 style block (both paragraphs, as plain text) and the §4.2 expressions' wording, from the brief."""
    text = open(BRIEF, encoding="utf-8").read()
    start = text.index("### 2.2 ")
    end = text.index("### 2.3 ", start)
    quoted = [line[2:] if line.startswith("> ") else "" for line in text[start:end].splitlines()
              if line.startswith(">")]
    paragraphs = " ".join(line if line else "\n\n" for line in quoted)
    style = re.sub(r" *\n\n *", "\n\n", paragraphs).strip()
    style = style.replace("exactly the colour I name", "exactly #00FF00 green")
    if not style.startswith("STYLE.") or "AVOID." not in style:
        raise SystemExit("portrait_prompts: couldn't read the style block from the brief's §2.2")

    start = text.index("### 4.2 ")
    end = text.index("### 4.3 ", start)
    wording = {}
    for line in text[start:end].splitlines():
        m = re.match(r"\| `(\w+)` \|[^|]*\| (.+?) \|$", line)
        if m:
            wording[m.group(1)] = m.group(2).rstrip(".") + "."
    missing = {e for tier in TIERS.values() for e in tier} - set(wording)
    if missing:
        raise SystemExit("portrait_prompts: the brief's §4.2 has no wording for " + ", ".join(sorted(missing)))
    return style, wording


def check_cast(cast):
    """Every character has what a card needs, and ids are unique."""
    seen = set()
    problems = []
    for c in cast:
        who = c.get("id", "?")
        for key in ("id", "name", "role", "group", "tier", "template", "look", "mood"):
            if not c.get(key):
                problems.append(f"{who}: no {key}")
        if c.get("group") not in GROUPS:
            problems.append(f"{who}: group {c.get('group')!r} isn't one of {GROUPS}")
        if c.get("tier") not in TIERS:
            problems.append(f"{who}: tier {c.get('tier')!r} isn't one of {list(TIERS)}")
        if c.get("template") not in TEMPLATES:
            problems.append(f"{who}: template {c.get('template')!r} isn't male or female")
        for e in c.get("wording", {}):
            if e not in TIERS["main"] + ["neutral"]:
                problems.append(f"{who}: wording for an unknown expression {e!r}")
        ids = [who] + [v.get("id") for v in c.get("variants", [])]
        for i in ids:
            if i in seen:
                problems.append(f"{i}: used twice")
            seen.add(i)
        for v in c.get("variants", []):
            if not v.get("id") or not v.get("change"):
                problems.append(f"{who}: a variant with no id or change")
            for e in v.get("expressions", []):
                if e not in TIERS["main"]:
                    problems.append(f"{v.get('id')}: unknown expression {e!r}")
    return problems


def fence(text):
    return "```text\n" + text.strip() + "\n```\n"


def edit(expression_line, save, keep, base):
    return (f"Edit {base}: change ONLY the expression, to the one below. Move only the eyes, "
            f"eyebrows, nose, mouth and cheeks, and the head no more than the expression needs. {keep}, the colours, "
            f"the size and the position of everything else stay exactly the same, and the face keeps looking "
            f"straight at the viewer. Keep it real pixel art on the same grid of big pixels, on the same flat #00FF00 "
            f"background. "
            f"Give it back at exactly 1024 by 1024.\n"
            f"EXPRESSION. {expression_line}\n"
            f"I'll save it as {save}.")


def card(c, style, wording):
    """One character's section."""
    keep = c.get("keep", "The hair, the clothes")
    out = [f"# {c['name']} · `{c['id']}`\n\n",
           GENERATED,
           f"{c['role']}\n\n",
           f"**Tier:** {c['tier']} ({len(TIERS[c['tier']]) + 1} expressions). "
           f"**Save to:** `tools/source/pixel/portraits/{c['id']}/`. How to use this file, and the fixes for a "
           f"picture that comes back wrong: [README](README.md).\n\n",
           f"**New chat.** **Attach:** `tools/source/pixel/templates/portrait-template-{c['template']}.png`"
           + "".join(f", and `{a}`" for a in c.get("attach", [])) + ". Paste:\n\n"]
    character = f"CHARACTER. {c['look'].strip()} The feel of the face: {c['mood'].strip().rstrip('.')}."
    extra = "\n\n" + c["note"].strip() if c.get("note") else ""
    neutral = c.get("wording", {}).get("neutral", NEUTRAL)
    out.append(fence(f"{style}\n\n{SIZE}\n\n{character}{extra}\n\nEXPRESSION. {neutral}\n\n"
                     f"I'll save it as portrait-{c['id']}.neutral.png."))
    out.append(f"\nThen, **in the same chat, one message each**:\n")
    for e in TIERS[c["tier"]]:
        line = c.get("wording", {}).get(e, wording[e])
        out.append(f"\n`portrait-{c['id']}.{e}.png`\n\n")
        out.append(fence(edit(line, f"portrait-{c['id']}.{e}.png", keep,
                              "the neutral portrait (the first one you made in this chat)")))
    for v in c.get("variants", []):
        out.append(f"\n## Variant `{v['id']}`\n\n{v.get('when', '')} Same chat, after the expressions.\n\n")
        out.append(fence(
            f"Go back to the neutral portrait (portrait-{c['id']}.neutral.png) and edit it: {v['change'].strip()} "
            f"Keep the face, the neutral expression, the grid of big pixels, the size, the position and the flat "
            f"#00FF00 background exactly the same, still facing the viewer. Give it back at exactly 1024 by 1024.\n"
            f"I'll save it as portrait-{v['id']}.neutral.png."))
        for e in v.get("expressions", []):
            line = c.get("wording", {}).get(e, wording[e])
            out.append(f"\n`portrait-{v['id']}.{e}.png`\n\n")
            out.append(fence(edit(line, f"portrait-{v['id']}.{e}.png", keep,
                                  f"the {v['id']} neutral portrait (the first {v['id']} picture you made)")))
    return "".join(out)


MASTER = "ALL-PORTRAITS-for-ChatGPT.md"


def master(cast, style, wording):
    """One file for ChatGPT itself: the rules once, then every picture numbered, character by character."""
    order = sorted(cast, key=lambda c: (c["id"] != "brannock", GROUPS.index(c["group"])))
    out = [
        "# LegendQuest: every character's close-up portrait (instructions for ChatGPT)\n\n",
        "## How we'll work\n\n",
        "I've attached this file and two template pictures: portrait-template-male.png and "
        "portrait-template-female.png. Make the pictures listed below **one at a time, in order, one picture per "
        "message**. When I say \"next\", make the next picture on the list. When I say \"do #N\", make picture N. "
        "Before each picture, write its number and its file name; after it, stop and wait. Never put more than one "
        "portrait in a picture, and never write text in a picture.\n\n",
        "- A **neutral** picture is painted fresh on the character's template (male or female, as listed).\n",
        "- Every **expression** picture is an edit of that character's neutral picture (or the variant's neutral "
        "picture): change ONLY the expression. Move only the eyes, eyebrows, nose, mouth and cheeks, and the head "
        "no more than the expression needs. The face, hair, clothes, colours, pixels, size and position stay exactly "
        "the same, and the face keeps looking straight at the viewer.\n",
        "- A **variant** picture is an edit of the character's neutral picture: change only what the variant says, "
        "keeping the face, the neutral expression, the pixels, the size and the position.\n",
        "- Every picture is exactly 1024 by 1024 pixels on flat #00FF00 green.\n\n",
        "## The style (every picture)\n\n",
        style.replace("\n\n", "\n\n") + "\n\n",
        "## The size and framing (every picture)\n\n",
        SIZE.replace("The attached picture is the template", "The template (male or female, as the character's "
                     "entry says) is") + "\n\n",
        "## The expressions\n\n",
        f"- **neutral**: {NEUTRAL}\n",
    ]
    for e in TIERS["main"]:
        out.append(f"- **{e}**: {wording[e]}\n")
    out.append("\n## The pictures\n\n")
    n = 0
    for c in order:
        out.append(f"### {c['name']} (`{c['id']}`), template: {c['template']}\n\n")
        out.append(f"CHARACTER. {c['look'].strip()} The feel of the face: {c['mood'].strip().rstrip('.')}.\n\n")
        if c.get("note"):
            out.append(c["note"].strip() + "\n\n")
        n += 1
        first = n
        out.append(f"{n}. `portrait-{c['id']}.neutral.png`: neutral, painted on the {c['template']} template\n")
        for e in TIERS[c["tier"]]:
            n += 1
            special = c.get("wording", {}).get(e)
            out.append(f"{n}. `portrait-{c['id']}.{e}.png`: {e}, an edit of #{first}"
                       + (f" ({special})" if special else "") + "\n")
        for v in c.get("variants", []):
            n += 1
            vfirst = n
            out.append(f"{n}. `portrait-{v['id']}.neutral.png`: variant, an edit of #{first}. {v.get('when', '')} "
                       f"Change: {v['change'].replace('change the look: ', '').strip()}\n")
            for e in v.get("expressions", []):
                n += 1
                out.append(f"{n}. `portrait-{v['id']}.{e}.png`: {e}, an edit of #{vfirst}\n")
        out.append("\n")
    out.insert(2, f"{len(cast)} characters, {n} pictures. Brannock comes first: he's the test, so after his six "
                  "pictures (#1 to #6) I'll check them before we go on.\n\n")
    return "".join(out)


def build():
    style, wording = read_brief()
    cast = json.load(open(CAST, encoding="utf-8"))
    problems = check_cast(cast)
    if problems:
        raise SystemExit("portrait_prompts: the cast list has problems:\n  " + "\n  ".join(problems))

    def pictures(c):
        return (1 + len(TIERS[c["tier"]])
                + sum(1 + len(v.get("expressions", [])) for v in c.get("variants", [])))

    total = sum(pictures(c) for c in cast)
    files = {}
    head = [
        "# Pixel art: every character's close-up portrait (ready-to-paste ChatGPT prompts)\n\n",
        GENERATED,
        "A front-facing, chest-up pixel portrait for every character with a personal quest or real dialogue: the "
        "companions, the main story, the villains and bosses who speak, and the named supporting cast. They're the "
        "faces in the dialogue box and in cutscene close-ups (`docs/pixel-art-brief.md` §4). The player and {sb} "
        "aren't here: their faces are the layered kit (brief §4.6, `docs/pixel-art-batch-1.md` §2).\n\n",
        "**How to use it.** Each character has a file here. Open it, start a **new chat** in ChatGPT, attach the "
        "template it names (in `tools/source/pixel/templates/`), and paste the first block whole. Then stay in the "
        "**same chat** and paste each block after it in order, one message each, saving each picture under the "
        "name in the block's last line. Staying in one chat keeps the face, the pixels and the framing the same in "
        "every expression. If a picture comes back wrong, use a fix below and do it again.\n\n",
        f"**The whole list in one file:** [{MASTER}]({MASTER}). Upload it to ChatGPT with both templates, and "
        "say \"next\" for each picture. It has the same prompts as the character files, with the rules written "
        "once. Start a new chat every character or two: long chats drift.\n\n",
        "**Where the files go.** `tools/source/pixel/portraits/<id>/`, one folder per character (a variant's "
        "pictures go in its character's folder).\n\n",
        "**What to send Claude.** A character's whole set at a time. Claude snaps each picture to a true 96 × 96 "
        "pixel grid, cleans the palette, and animates it (blinking, talking, breathing, the expression changes, "
        "brief §4.3). Brannock's set is the pilot (batch 1): send his first, in case the prompts need a change, then "
        "the companions, then the rest in the order below.\n\n",
        "Expressions by tier (brief §4.2): **main** all 13; **named** 8 (neutral, angry, disgust, smile, laugh, "
        "sad, shock, worried); **minor** 6 (neutral and the five: angry, disgust, smile, laugh, sad). A missing one "
        "falls back to the nearest, so a set works before it's finished.\n\n",
        f"**{len(cast)} characters, {total} pictures.**\n\n",
    ]
    for g in GROUPS:
        members = [c for c in cast if c["group"] == g]
        if not members:
            continue
        head.append(f"## {g} ({sum(pictures(c) for c in members)} pictures)\n\n"
                    "| Character | Tier | Pictures | Variants |\n| --- | --- | --- | --- |\n")
        for c in members:
            vs = ", ".join(f"`{v['id']}`" for v in c.get("variants", [])) or "none"
            head.append(f"| [{c['name']}]({c['id']}.md) | {c['tier']} | {pictures(c)} | {vs} |\n")
            files[c["id"] + ".md"] = card(c, style, wording)
        head.append("\n")
    head += [
        "## Fix the size (use when a picture comes back wrong)\n\n",
        fence("That came back the wrong size or moved. Do it again, and give it back at exactly 1024 by 1024 pixels, "
              "with the character exactly where the grey mannequin is in the template: the eyes on the dashed eye "
              "line either side of the centre line, the chin on the chin line, the shoulders filling the bottom "
              "edge, the face looking straight at the viewer. Don't crop, zoom, turn, re-centre or re-frame it. "
              "Everything else stays exactly as it was."),
        "\n## Fix the pixels (use when a picture comes back smooth or with tiny pixels)\n\n",
        fence("That looks too smooth and detailed. Redo it as real low-resolution pixel art: a grid of about 96 by 96 "
              "big square pixels, each about 10 to 11 image pixels wide and one flat colour, with no blending "
              "between them, a small palette, and a one-pixel dark brown-violet outline. Keep the character, the "
              "expression, the size and the position exactly the same."),
        "\n## Fix the face (use when an expression changed who it is)\n\n",
        fence("That changed the character's face, hair or clothes. Go back to the neutral portrait and change ONLY the "
              "expression this time: the same person, the same hair, clothes, colours, pixels, size and position, "
              "still looking straight at the viewer."),
    ]
    files[MASTER] = master(cast, style, wording)
    files["README.md"] = "".join(head)
    return files


def main(argv):
    files = build()
    existing = {n for n in os.listdir(OUT) if n.endswith(".md")} if os.path.isdir(OUT) else set()
    if "--check" in argv:
        stale = [n for n, text in files.items() if not os.path.exists(os.path.join(OUT, n))
                 or open(os.path.join(OUT, n), encoding="utf-8").read() != text]
        stale += sorted(existing - set(files))
        if stale:
            print("portrait_prompts: docs/pixel-art-portraits/ is out of date (" + ", ".join(stale[:5])
                  + (", ..." if len(stale) > 5 else "") + "); run tools/pixel/portrait_prompts.py")
            return 1
        print("portrait_prompts: up to date")
        return 0
    os.makedirs(OUT, exist_ok=True)
    for name in existing - set(files):
        os.remove(os.path.join(OUT, name))
    for name, text in files.items():
        with open(os.path.join(OUT, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"portrait_prompts: wrote {len(files)} files to docs/pixel-art-portraits/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
